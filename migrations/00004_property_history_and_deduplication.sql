CREATE VIEW duplicate_decision_inspection AS
SELECT d.id,
       d.rule_version,
       d.confidence,
       d.automatic_status,
       d.status,
       d.evidence,
       d.evaluated_at,
       d.overridden_at,
       d.override_reason,
       left_listing.source AS left_source,
       left_listing.external_id AS left_external_id,
       right_listing.source AS right_source,
       right_listing.external_id AS right_external_id,
       left_membership.property_id AS left_property_id,
       right_membership.property_id AS right_property_id
FROM duplicate_decisions d
JOIN listings left_listing ON left_listing.id = d.left_listing_id
JOIN listings right_listing ON right_listing.id = d.right_listing_id
LEFT JOIN property_listing_memberships left_membership
       ON left_membership.listing_id = d.left_listing_id AND left_membership.valid_to IS NULL
LEFT JOIN property_listing_memberships right_membership
       ON right_membership.listing_id = d.right_listing_id AND right_membership.valid_to IS NULL;

CREATE VIEW duplicate_score_distribution AS
SELECT rule_version,
       status,
       least(20, width_bucket(confidence, 0::DOUBLE PRECISION, 1::DOUBLE PRECISION, 20)) AS score_bucket,
       count(*) AS decision_count
FROM duplicate_decisions
GROUP BY rule_version, status, score_bucket;


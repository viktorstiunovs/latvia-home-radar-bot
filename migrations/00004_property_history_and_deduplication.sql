CREATE TABLE duplicate_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    left_listing_id BIGINT NOT NULL REFERENCES listings(id),
    right_listing_id BIGINT NOT NULL REFERENCES listings(id),
    left_snapshot_id BIGINT NOT NULL REFERENCES listing_signal_snapshots(id),
    right_snapshot_id BIGINT NOT NULL REFERENCES listing_signal_snapshots(id),
    rule_version TEXT NOT NULL,
    confidence DOUBLE PRECISION NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
    automatic_status TEXT NOT NULL CHECK (automatic_status IN ('accepted', 'ambiguous', 'rejected')),
    status TEXT NOT NULL CHECK (status IN ('accepted', 'ambiguous', 'rejected')),
    evidence JSONB NOT NULL,
    evaluated_at TIMESTAMPTZ NOT NULL,
    overridden_at TIMESTAMPTZ,
    override_reason TEXT,
    CHECK (left_listing_id < right_listing_id),
    CHECK (left_snapshot_id <> right_snapshot_id),
    UNIQUE (left_snapshot_id, right_snapshot_id, rule_version)
);

